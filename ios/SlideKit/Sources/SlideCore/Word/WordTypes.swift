import Foundation

/// Port of src/core/types.ts (WORD SLIDE).
public enum WordConst {
    public static let size = 4
    public static let cells = 16
    public static let generatorVersion = "g2"
}

public enum WordDifficulty: String, Codable, CaseIterable, Sendable { case easy, normal, hard }
public enum WordMode: String, Codable, Sendable { case daily, endless }
public enum WordMark: String, Codable, Sendable { case green, yellow, gray }
public enum WordDirection: String, Codable, Sendable { case up, down, left, right }

public struct WordTile: Codable, Equatable, Sendable {
    /// Stable identity (animation); equals the tile's cell index on the initial board.
    public var id: Int
    public var letter: String
    public init(id: Int, letter: String) { self.id = id; self.letter = letter }
}
public typealias WordBoard = [WordTile?]

public struct WordEntry: Codable, Equatable, Sendable {
    public var word: String
    public var category: String
    public var definition: String
    public init(word: String, category: String, definition: String) { self.word = word; self.category = category; self.definition = definition }
}

public struct WordSet: Codable, Equatable, Sendable {
    /// Three 4-letter words (any order on the board).
    public var top: [String]
    /// 3-letter word in the left 3 cells of the bottom row.
    public var bottom: String
    public init(top: [String], bottom: String) { self.top = top; self.bottom = bottom }
    public var all: [String] { top + [bottom] }
}

public struct WordPuzzle: Codable, Equatable, Sendable {
    public var id: String
    public var mode: WordMode
    public var difficulty: WordDifficulty
    public var number: Int?
    public var words: WordSet
    /// clues[0..2] = words.top[0..2], clues[3] = words.bottom
    public var clues: [WordEntry]
    public var letters: [String?]
    public var solution: [Int]
    public var generatorVersion: String
    public var wordsVersion: String
}

/// Word lists (generated by ios/scripts/export-word.ts from src/data/words.ts).
public struct WordCatalog: Sendable {
    public let version: String
    public let four: [WordDifficulty: [WordEntry]]
    public let three: [WordDifficulty: [WordEntry]]

    struct Raw: Decodable { var version: String; var four: [String: [WordEntry]]; var three: [String: [WordEntry]] }

    public init(version: String, four: [WordDifficulty: [WordEntry]], three: [WordDifficulty: [WordEntry]]) {
        self.version = version; self.four = four; self.three = three
    }

    public init(url: URL) throws {
        let raw = try JSONDecoder().decode(Raw.self, from: Data(contentsOf: url))
        func conv(_ m: [String: [WordEntry]]) -> [WordDifficulty: [WordEntry]] {
            var o: [WordDifficulty: [WordEntry]] = [:]
            for d in WordDifficulty.allCases { o[d] = m[d.rawValue] ?? [] }
            return o
        }
        self.init(version: raw.version, four: conv(raw.four), three: conv(raw.three))
    }

    /// Entries usable at a difficulty (easy: easy; normal: easy+normal; hard: normal+hard).
    public static func pool(_ list: [WordDifficulty: [WordEntry]], _ d: WordDifficulty) -> [WordEntry] {
        switch d {
        case .easy: return list[.easy] ?? []
        case .normal: return (list[.easy] ?? []) + (list[.normal] ?? [])
        case .hard: return (list[.normal] ?? []) + (list[.hard] ?? [])
        }
    }
}
